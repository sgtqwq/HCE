const i32 PhaseValue[6] = {0, 357, 398, 482, 1081, 0};

void refresh_evaluation(Position& pos) {
	pos.psqt_score = 0;
	pos.phase_score = 0;

	for (i32 pt = Pawn; pt <= King; ++pt) {
		u64 us = pos.colour[0] & pos.pieces[pt];
		u64 them = pos.colour[1] & pos.pieces[pt];
		pos.phase_score += PhaseValue[pt] * BB::popcount(us | them);

		while (us) pos.psqt_score += Psqt[pt][BB::pop_lsb(us)];
		while (them) pos.psqt_score -= Psqt[pt][BB::pop_lsb(them) ^ 56];
	}
}

i32 evaluate(const Position& pos) {
	constexpr i32 OpeningPhase = 7756;
	constexpr i32 EndgamePhase = 533;
	const i32 mg = mg_of(pos.psqt_score);
	const i32 eg = eg_of(pos.psqt_score);

	if (pos.phase_score > OpeningPhase) return mg;
	if (pos.phase_score < EndgamePhase) return eg;
	return (mg * pos.phase_score + eg * (OpeningPhase - pos.phase_score)) / OpeningPhase;
}
